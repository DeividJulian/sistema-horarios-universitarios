import { Injectable, inject } from '@angular/core';
import { Code, ConnectError, Interceptor, createClient } from '@connectrpc/connect';
import { createConnectTransport } from '@connectrpc/connect-web';

import { API_URL } from '../api/api-url';
import { AuthService } from '../auth/auth.service';
import { GenerationEvent, ListScheduleResponse, ScheduleService } from './gen/horarios/v1/horarios_pb';

/** Base URL of the RPC service, mounted by the backend under /rpc. */
export const RPC_URL = `${API_URL}/rpc`;

/** Spanish message for an RPC error (the server already writes its messages in Spanish). */
export function rpcErrorMessage(error: unknown, fallback: string): string {
  if (error instanceof ConnectError) {
    if (error.code === Code.Canceled) return 'La generación se canceló: el horario anterior se conserva.';
    if (error.code === Code.Unavailable || (error.code === Code.Unknown && !error.rawMessage)) {
      return 'No se pudo conectar con el servidor. Revisa tu conexión o intenta de nuevo en un minuto.';
    }
    if (error.rawMessage) return error.rawMessage;
  }
  return fallback;
}

/**
 * Client of proto/horarios/v1/horarios.proto with the code generated by protoc-gen-es. It speaks the Connect protocol
 * with Protobuf binary, so it works from the browser over HTTP/1.1 (Render) and supports server streaming.
 */
@Injectable({ providedIn: 'root' })
export class ScheduleRpcService {
  private readonly auth = inject(AuthService);

  /** The same session as REST: the JWT travels as request metadata (Authorization header). */
  private readonly withSession: Interceptor = (next) => async (request) => {
    const token = this.auth.token();
    if (token) request.header.set('Authorization', `Bearer ${token}`);
    try {
      return await next(request);
    } catch (error) {
      if (error instanceof ConnectError && error.code === Code.Unauthenticated && this.auth.isLoggedIn()) {
        this.auth.logout();
      }
      throw error;
    }
  };

  private readonly client = createClient(
    ScheduleService,
    createConnectTransport({ baseUrl: RPC_URL, useBinaryFormat: true, interceptors: [this.withSession] }),
  );

  /** Streams the progress of the generation; aborting the signal cancels it (nothing is saved). */
  generate(signal: AbortSignal): AsyncIterable<GenerationEvent> {
    return this.client.generateSchedule({}, { signal });
  }

  listSchedule(): Promise<ListScheduleResponse> {
    return this.client.listSchedule({});
  }

  /** A client whose responses are measured (bytes of the body), for the REST vs gRPC comparison. */
  measuredClient(onBytes: (bytes: number) => void) {
    const measure: typeof fetch = async (input, init) => {
      const response = await fetch(input, init);
      const body = await response.arrayBuffer();
      onBytes(body.byteLength);
      return new Response(body, { status: response.status, statusText: response.statusText, headers: response.headers });
    };
    return createClient(
      ScheduleService,
      createConnectTransport({ baseUrl: RPC_URL, useBinaryFormat: true, interceptors: [this.withSession], fetch: measure }),
    );
  }
}
